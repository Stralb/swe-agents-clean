from pathlib import Path

from src.pipeline.case_exporter import database_export_zip
from ui.retrieval import (
    BASE_QUERY,
    ai_marker_label,
    derive_query_terms,
    derive_stage,
    filter_by_terms,
    generated_query,
    priority_score,
    signal_label,
    row_signal_label,
)


def test_generated_query_stays_structural_and_does_not_add_indicator_terms():
    assert generated_query('"requirements.txt"') == BASE_QUERY


def test_issue_link_indicator_does_not_change_structural_query():
    assert generated_query('same-repo linked issue') == BASE_QUERY


def test_derive_query_terms_from_files_and_ai_markers():
    row = {
        "issue_title": "CI failing",
        "issue_body": "please check GitHub Actions env",
        "pr_title": "Fix workflow",
        "pr_body": "Generated by Claude Code",
        "file_names": "requirements.txt,.github/workflows/test.yml,src/auth/token.py",
        "ai_marker_terms": "Claude Code",
    }
    terms = derive_query_terms(row)
    assert '"Claude Code"' in terms
    assert '"requirements.txt"' in terms
    assert '".github/workflows"' in terms
    assert '"requirements.txt"' in terms


def test_filter_by_terms_any_and_all_modes():
    row_terms = ['"Claude Code"', '"requirements.txt"']
    assert filter_by_terms(row_terms, ['"Claude Code"', '"env"'], "any")
    assert not filter_by_terms(row_terms, ['"Claude Code"', '"env"'], "all")
    assert filter_by_terms(row_terms, ['"Claude Code"', '"requirements.txt"'], "all")


def test_stage_signal_ai_and_priority_labels():
    row = {
        "status": "needs_review",
        "final_label": "Unclear",
        "downstream_signal": "secret,dependency",
        "ai_marker_terms": "Claude Code",
        "file_names": ".github/workflows/test.yml,requirements.txt",
        "issue_body": "steps to reproduce",
    }
    assert derive_stage(row) == "Needs review"
    assert signal_label(row["downstream_signal"]) == "Secret/CI + Dependency"
    assert ai_marker_label(row) == "Claude Code"
    assert priority_score(row) >= 12


def test_database_export_zip_contains_db_and_methodology(tmp_path: Path):
    db_path = tmp_path / "miner.db"
    with sqlite3.connect(db_path) as conn:
        conn.execute("CREATE TABLE example(id INTEGER PRIMARY KEY)")
        conn.execute("INSERT INTO example(id) VALUES (1)")
    config = tmp_path / "config.yml"
    config.write_text("database:\n  path: data/miner.db\n", encoding="utf-8")
    payload = database_export_zip(db_path, config_path=config, export_name="pilot run", project_root=tmp_path)
    with zipfile.ZipFile(BytesIO(payload)) as zf:
        names = set(zf.namelist())
    assert "pilot_run/miner.db" in names
    assert "pilot_run/config.yml" in names
    assert "pilot_run/methodology_snapshot.json" in names
    assert "pilot_run/README_EXPORT.md" in names


def test_clean_case_with_empty_signal_displays_clean_not_pending():
    row = {"status": "scanned_clean", "downstream_signal": None}
    assert row_signal_label(row) == "Clean"
    assert signal_label(None, "scanned_clean") == "Clean"


def test_unfinished_case_with_empty_signal_displays_pending():
    row = {"status": "scanner_running", "downstream_signal": None}
    assert row_signal_label(row) == "Pending"
